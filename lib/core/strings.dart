/// All app text in three languages: English (en), Hindi (hi), Hinglish (hn).
/// Each entry is [english, hindi, hinglish].
class Strings {
  static String lang = 'en';
}

String tr(String key) {
  final v = _t[key];
  if (v == null) return key;
  final i = switch (Strings.lang) { 'hi' => 1, 'hn' => 2, _ => 0 };
  return v[i].isEmpty ? v[0] : v[i];
}

/// Text with {placeholders} filled in.
String trf(String key, Map<String, String> args) {
  var s = tr(key);
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

